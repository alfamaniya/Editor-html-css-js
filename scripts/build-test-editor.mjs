#!/usr/bin/env node
/**
 * Build index-test-etitor.html as a standalone copy of the editor.
 *
 * Sources: index.html, style.css, smart-import.css, and the eight JavaScript files listed below.
 * Run locally: node scripts/build-test-editor.mjs
 * GitHub Actions runs this builder on every push to main.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'index-test-etitor.html');
const htmlPath = resolve(root, 'index.html');
const cssPath = resolve(root, 'style.css');
const smartImportCssPath = resolve(root, 'smart-import.css');
const scriptFiles = [
    'html-suggestions.js',
    'css-suggestions.js',
    'js-suggestions.js',
    'next-word-suggestions.js',
    'starter-gallery.js',
    'script.js',
    'word-tree.js',
    'smart-import.js',
    'github-update.js'
];

async function readText(path) {
    return readFile(path, 'utf8');
}

function replaceExactlyOnce(source, regex, replacement, label) {
    const flags = regex.flags.includes('g') ? regex.flags : regex.flags + 'g';
    const matches = source.match(new RegExp(regex.source, flags)) || [];
    if (matches.length !== 1) {
        throw new Error('Expected exactly one ' + label + '; found ' + matches.length + '.');
    }
    return source.replace(regex, () => replacement);
}

function escapeInlineScript(source) {
    // The HTML parser ends a script at a literal </script, even inside JS strings.
    // Escaping its slash keeps the generated script syntactically equivalent.
    return source.replace(/<\/script/gi, (match) => '<\\/' + match.slice(2));
}

function escapeInlineStyle(source) {
    // Protect the style element boundary if a CSS string ever contains </style.
    return source.replace(/<\/style/gi, (match) => '<\\/' + match.slice(2));
}

async function build() {
    let html = await readText(htmlPath);
    const css = await readText(cssPath);
    const smartImportCss = await readText(smartImportCssPath);

    // Add the generator banner while index.html is still pure markup.
    // JavaScript strings may contain sample DOCTYPE text after scripts are inlined.
    const banner = '<!-- AUTO-GENERATED by scripts/build-test-editor.mjs. Edit the source files, not this bundle. -->';
    html = replaceExactlyOnce(
        html,
        /<!doctype\s+html\s*>/i,
        (html.match(/<!doctype\s+html\s*>/i) || ['<!DOCTYPE html>'])[0] + '\n' + banner,
        'DOCTYPE declaration'
    );

    html = replaceExactlyOnce(
        html,
        /<link\b[^>]*href=["']style\.css["'][^>]*>/i,
        '<style data-bundled-from="style.css">\n' + escapeInlineStyle(css) + '\n</style>',
        'stylesheet reference to style.css'
    );

    html = replaceExactlyOnce(
        html,
        /<link\b[^>]*href=["']smart-import\.css["'][^>]*>/i,
        '<style data-bundled-from="smart-import.css">\n' + escapeInlineStyle(smartImportCss) + '\n</style>',
        'stylesheet reference to smart-import.css'
    );

    for (const filename of scriptFiles) {
        const script = await readText(resolve(root, filename));
        const escapedFilename = filename.replace(/\./g, '\\.');
        const scriptTag = new RegExp(
            '<script\\s+src="' + escapedFilename + '"\\s*>\\s*</script>',
            'i'
        );
        html = replaceExactlyOnce(
            html,
            scriptTag,
            '<script data-bundled-from="' + filename + '">\n' +
                escapeInlineScript(script) + '\n</script>',
            'script reference to ' + filename
        );
    }

    await writeFile(outputPath, html, 'utf8');
    console.log('Built ' + outputPath + ' (' + Buffer.byteLength(html, 'utf8') + ' bytes).');
}

build().catch((error) => {
    console.error('Could not build the standalone test editor:', error);
    process.exitCode = 1;
});
